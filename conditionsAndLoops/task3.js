//Завдання 3: Генерація таблиці множення 

//Використовуючи цикл for
const number = 2;

for (let i = 1; i <= 10; i++) {
    console.log(number + " x " + i + " = " + number * i);
}

//Використовуючи цикл while
const number = 3;
let i = 1;

while (i <= 10) {
    console.log(number + " x " + i + " = " + number * i);
    i++;
}
